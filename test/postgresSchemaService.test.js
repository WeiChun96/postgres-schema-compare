const assert = require('node:assert/strict');
const test = require('node:test');
const { PostgresSchemaService } = require('../out/services/postgresSchemaService');

test('table scripting reads the actual identity sequence name from PostgreSQL catalogs', async () => {
  const service = new PostgresSchemaService({ host: '', port: 5432, database: '', username: '', password: '' });
  let query;
  let parameters;
  const client = {
    query: async (sql, values) => {
      query = sql;
      parameters = values;
      return { rows: [{ ddl: 'CREATE TABLE public.employee (employee_id bigint GENERATED BY DEFAULT AS IDENTITY);' }] };
    }
  };

  await service.queryTableDefinition(client, { kind: 'table', schema: 'public', name: 'employee' });

  assert.deepEqual(parameters, ['public', 'employee']);
  assert.match(query, /ownership\.deptype = 'i'/);
  assert.match(query, /join pg_class sequence_relation on sequence_relation\.oid = sequence_settings\.seqrelid/);
  assert.match(query, /identity_sequence\.relname = format\('%s_%s_seq', t\.relname, a\.attname\)/);
  assert.match(query, /format\('SEQUENCE NAME %I\.%I ', identity_sequence\.nspname, identity_sequence\.relname\)/);
});
